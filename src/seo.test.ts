import { test, expect } from 'bun:test'
import type { RenderPlan } from './config.js'
import { findRelativeUrls, isNotFoundOutput, parseGitLog, renderRobots } from './seo.js'

test('isNotFoundOutput - matches the root and language 404 pages only', () => {
  expect(isNotFoundOutput('404.html', ['en', 'fr'])).toBe(true)
  expect(isNotFoundOutput('fr/404.html', ['en', 'fr'])).toBe(true)
  expect(isNotFoundOutput('de/404.html', ['en', 'fr'])).toBe(false)
  expect(isNotFoundOutput('guides/404.html', ['en', 'fr'])).toBe(false)
  expect(isNotFoundOutput('404-errors.html', ['en'])).toBe(false)
})

test('parseGitLog - keeps the newest date per file', () => {
  const stdout = '\x012026-11-02\n\nabout.md\n\x012026-10-01\n\nabout.md\nfr/über.md\n'
  const dates = parseGitLog(stdout)
  expect(dates.get('about.md')).toBe('2026-11-02')
  expect(dates.get('fr/über.md')).toBe('2026-10-01')
})

test('findRelativeUrls - flags relative href, src and srcset values only', () => {
  const html = `
    <a href="/">home</a><a href="#top">top</a><a href="https://x.test/">x</a>
    <a href="//cdn.test/a.css">cdn</a><a href="mailto:a@b.test">mail</a>
    <a href="about">bad</a><img src='img/logo.png'>
    <img srcset="/a.png 1x, img/b.png 2x">`
  expect(findRelativeUrls(html)).toEqual(['about', 'img/logo.png', 'img/b.png'])
})

function robotsPlan(relativeOutput: string, noindex = false): RenderPlan {
  return {
    sourcePath: relativeOutput,
    outputPath: relativeOutput,
    relativeOutput,
    html: '',
    meta: {
      title: '',
      description: '',
      sidebarTitle: '',
      sidebarSummary: '',
      backLinkHref: '/',
      backLinkLabel: '',
      output: relativeOutput,
      noindex,
    },
  }
}

test('renderRobots - disallows each noindex page exactly and adds extras and the sitemap', () => {
  const robots = renderRobots(
    [robotsPlan('index.html'), robotsPlan('secret.html', true), robotsPlan('guides/index.html', true)],
    'https://example.com',
    { disallow: ['/drafts/'] },
  )
  expect(robots).toBe(
    [
      '# Generated by simple-markdown-builder',
      'User-agent: *',
      'Allow: /',
      'Disallow: /guides/$',
      'Disallow: /guides/index.html$',
      'Disallow: /secret$',
      'Disallow: /secret.html$',
      'Disallow: /drafts/',
      '',
      'Sitemap: https://example.com/sitemap.xml',
      '',
    ].join('\n'),
  )
})
