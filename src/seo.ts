const execFileAsync = promisify(execFile)

// GitHub Pages serves the root 404.html for any missing URL; a language's
// 404 page is built the same way so it gets the same treatment.
export function isNotFoundOutput(relativeOutput: string, supportedLangs: readonly string[]): boolean {
  return (
    relativeOutput === '404.html' ||
    supportedLangs.some((lang) => relativeOutput === `${lang}/404.html`)
  )
}

// One `git log` over the content directory, newest commit first, so the first
// date seen for a file is its last commit. Keys are paths relative to
// contentDir. Returns undefined, after one warning, when git cannot give
// trustworthy dates.
export async function gitLastModifiedDates(
  contentDir: string,
): Promise<Map<string, string> | undefined> {
  const git = (args: string[]) =>
    execFileAsync('git', ['-C', contentDir, ...args], { maxBuffer: 64 * 1024 * 1024 })

  try {
    const { stdout: shallow } = await git(['rev-parse', '--is-shallow-repository'])
    if (shallow.trim() === 'true') {
      logWarning(
        'lastmod: shallow git clone, so commit dates are unreliable and are omitted. ' +
          'Fetch full history (actions/checkout: fetch-depth: 0).',
      )
      return undefined
    }
    const { stdout } = await git([
      '-c',
      'core.quotePath=false',
      'log',
      '--format=%x01%cs',
      '--name-only',
      '--relative',
      '--',
      '.',
    ])
    return parseGitLog(stdout)
  } catch (error) {
    const stderr = (error as { stderr?: string }).stderr?.trim()
    const reason = stderr || (error instanceof Error ? error.message : String(error))
    logWarning(`lastmod: could not read git history, so dates are omitted (${reason.split('\n')[0]})`)
    return undefined
  }
}

export function parseGitLog(stdout: string): Map<string, string> {
  const dates = new Map<string, string>()
  for (const commit of stdout.split('\x01')) {
    const [date, ...files] = commit.split('\n')
    if (!date) continue
    for (const file of files) {
      if (file && !dates.has(file)) {
        dates.set(file, date.trim())
      }
    }
  }
  return dates
}

export function lastModifiedFor(
  dates: ReadonlyMap<string, string> | undefined,
  contentDir: string,
  sourcePath: string,
): string | undefined {
  return dates?.get(normalizePathSeparators(path.relative(contentDir, sourcePath)))
}

const ABSOLUTE_OR_ROOT = /^(?:[a-z][a-z0-9+.-]*:|\/|#)/i

// The 404 page is served at whatever URL was missing, so a relative URL in
// it resolves against that URL and breaks at any other depth.
export function findRelativeUrls(html: string): string[] {
  const found: string[] = []
  for (const match of html.matchAll(/\s(href|src|srcset)\s*=\s*(?:"([^"]*)"|'([^']*)')/gi)) {
    const value = (match[2] ?? match[3] ?? '').trim()
    const urls =
      match[1]!.toLowerCase() === 'srcset'
        ? value.split(',').map((candidate) => candidate.trim().split(/\s+/)[0] ?? '')
        : [value]
    for (const url of urls) {
      if (url && !ABSOLUTE_OR_ROOT.test(url)) {
        found.push(url)
      }
    }
  }
  return found
}

export function warnRelativeUrlsOnNotFound(html: string, relativeOutput: string): void {
  const relative = findRelativeUrls(html)
  if (relative.length > 0) {
    logWarning(
      `${relativeOutput} is served at any missing URL, so these relative URLs break below the site root; ` +
        `make them root-relative (/...): ${[...new Set(relative)].join(', ')}`,
    )
  }
}

export const ROBOTS_MARKER = '# Generated by simple-markdown-builder'

// Refuse to overwrite a robots.txt the site maintains by hand. Checked before
// any page is written so a failing build leaves the output untouched.
export async function assertRobotsWritable(outputDir: string): Promise<void> {
  const robotsPath = path.join(outputDir, 'robots.txt')
  let existing: string
  try {
    existing = await readFile(robotsPath, 'utf-8')
  } catch {
    return
  }
  if (!existing.startsWith(ROBOTS_MARKER)) {
    throw new Error(
      `${path.relative(process.cwd(), robotsPath)} exists and was not generated by simple-markdown-builder. ` +
        `Delete it to let the builder generate it, or set robots: false to keep it.`,
    )
  }
}

export function renderRobots(
  plans: readonly RenderPlan[],
  baseUrl: string,
  robots: true | RobotsConfig,
): string {
  // Disallow matches by prefix, so generated lines end in `$` to block only the
  // page itself, not a directory under it or a sibling sharing its prefix.
  const pageRules = plans
    .filter((plan) => isBooleanEnabled(plan.meta.noindex))
    .sort((a, b) => a.relativeOutput.localeCompare(b.relativeOutput))
    .flatMap((plan) => {
      const clean = `/${normalizeIndexUrl(stripHtmlExtension(plan.relativeOutput))}`
      const html = `/${plan.relativeOutput}`
      return clean === html ? [clean] : [clean, html]
    })
    .map((urlPath) => `Disallow: ${urlPath}$`)
  const extraRules = (robots === true ? [] : (robots.disallow ?? [])).map(
    (urlPath) => `Disallow: ${urlPath}`,
  )

  return [
    ROBOTS_MARKER,
    'User-agent: *',
    'Allow: /',
    ...pageRules,
    ...extraRules,
    '',
    `Sitemap: ${toAbsoluteUrl('sitemap.xml', baseUrl)}`,
    '',
  ].join('\n')
}

export async function writeRobots(
  plans: readonly RenderPlan[],
  outputDir: string,
  baseUrl: string,
  robots: true | RobotsConfig,
): Promise<void> {
  const robotsPath = path.join(outputDir, 'robots.txt')
  await writeFile(robotsPath, renderRobots(plans, baseUrl, robots))
  console.log(`Generated ${path.relative(process.cwd(), robotsPath)}`)
}
